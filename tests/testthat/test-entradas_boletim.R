test_that("leitura preserva identificadores e historico sem estimativas", {
  base <- system.file("extdata", "feira_livre", package = "infodengesubmunicipal")
  dados <- ler_tabela_local(file.path(base, "notificacoes.csv"))
  expect_equal(nrow(dados), 7210L)
  expect_type(dados$nu_notific, "character")
  expect_equal(sum(grepl("[^0-9]", dados$nu_notific)), 210L)
  h <- preparar_historico_alerta(file.path(base, "historico_alerta.csv"))
  expect_equal(sum(h$casos), 7210)
  expect_true(all(is.na(h$casos_est)))
  expect_equal(sum(is.na(h$Rt)), 36L)
  separado <- tempfile(fileext = ".rds")
  saveRDS(dplyr::select(h, -"arbo"), separado)
  expect_equal(nrow(preparar_historico_alerta(path_dengue = separado)), 90L)
  saveRDS(dplyr::bind_rows(h, h[1, ]), separado)
  expect_error(preparar_historico_alerta(separado), "duplicadas")
})
test_that("referencia sintetica tem geometria e populacao completas", {
  base <- system.file("extdata", "feira_livre", package = "infodengesubmunicipal")
  ref <- sf::st_read(file.path(base, "shape", "feira_livre_bairros.shp"), options = "ENCODING=UTF-8", quiet = TRUE)
  path <- tempfile(fileext = ".rds"); saveRDS(ref, path)
  r <- preparar_referencia(path, "nm_bairro", "id_bairro", "nm_distr", "pop", attr(ref, "sf_column"))
  expect_s3_class(r, "sf")
  expect_equal(nrow(r), 28L)
  expect_equal(length(unique(r$distrito)), 4L)
  expect_equal(sum(r$pop), 249990)
  expect_true("TILAPIA" %in% r$nome_bairr)
  saveRDS(r[c(1, 1), ], path)
  expect_error(preparar_referencia(path, "nome_bairr", "id_bairro", "distrito", "pop", "geometry"), "unicos")
})
