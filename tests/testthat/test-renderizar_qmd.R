test_that("renderizacao preserva mensagem de LaTeX e caminho com espacos", {
  skip_on_os("windows")
  pasta <- tempfile("boletim com espacos "); dir.create(pasta)
  qmd <- file.path(pasta, "boletim.qmd"); writeLines("teste", qmd)
  bin <- file.path(pasta, "quarto-falso")
  writeLines(c("#!/bin/sh", "exit 0"), bin); Sys.chmod(bin, "0755")
  expect_equal(renderizar_qmd(qmd, bin), normalizePath(qmd))
  expect_error(renderizar_qmd(qmd, ""), "Quarto nao encontrado")
  writeLines(c("#!/bin/sh", "exit 1"), bin)
  expect_error(renderizar_qmd(qmd, bin), "nenhum log")
  log <- sub("qmd$", "log", qmd)
  writeLines(c("! Logo ausente {captions}", "detalhe"), log)
  expect_message(expect_error(renderizar_qmd(qmd, bin), "status 1"), "Logo ausente {captions}", fixed = TRUE)
})
